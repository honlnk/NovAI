export const INIT_NOVEL_PROMPT = `请初始化并更新本小说项目的项目总览文件 prompts/NovAI.md。

项目总览是项目级累积记忆，每轮 Agent 运行都会读取它作为上下文。它的作用是让 Agent 在任何一轮都知道“这部书写到哪了、有哪些人物和设定、哪些伏笔待回收、风格约定是什么”，而不必每次从零翻文件。

请按下面的阶段执行。

## 阶段 1：扫描项目，盘点现状

先用工具摸清项目当前状态，不要凭空编造：

- 用 ListDirectory 查看 chapters/、elements/、prompts/ 的目录结构，了解有哪些章节和要素。
- 用 FindFiles（模式 chapters/*.txt）盘点已写章节的数量和命名规律。
- 用 ReadFile 精读最近 2~3 章正文，掌握当前主线走向、最新出场人物和未解决的冲突。
- 如果项目已有要素索引，用 RagSearch 按自然语言召回主要人物、地点、实体、剧情、世界观设定和已埋设的伏笔；对召回结果里有价值的 sourcePath 再用 ReadFile 精读补全。
- 用 ReadFile 读取 prompts/system.md，了解已有的文风、人称、视角、格式约定。
- 如果 prompts/NovAI.md 已存在，必须先用 ReadFile 读取它的现有内容，避免覆盖用户手动维护的部分。

## 阶段 2：生成或更新 prompts/NovAI.md

根据阶段 1 的发现，把项目总览写入 prompts/NovAI.md。必须包含以下段落，每段只写能从项目内容推导出来的事实：

- 作品概述：一句话简介（logline）、题材类型（如玄幻/武侠/都市/科幻）、当前状态（连载中/已完结/停更）。
- 章节进度：已完成章节数、当前主线（最近在推进什么剧情）、当前卡点或待解决的冲突。
- 主要人物：列出已出场的主要人物，每人附核心身份、核心动机和当前的剧情弧光位置。只写已登场角色，不写计划中尚未出场的。
- 世界观速览：作品涉及的核心世界观设定（时代背景、势力格局、修行或能力体系等）。只写已经在章节里建立起来的设定。
- 伏笔追踪：列出已埋设但尚未回收的伏笔，以及已回收的伏笔。如果项目里还看不出明确伏笔，写“暂无明确伏笔”，不要编造。
- 风格约定：从 system.md 和正文里总结的叙事人称、时态、文风倾向、禁用词或格式习惯。

## 写作要求

- 写文件用 CreateFile（文件不存在时）或 EditFile（文件已存在、阶段 1 已读取过原文时）。不要用 CreateFile 覆盖已存在的文件。
- 如果 prompts/NovAI.md 已存在，基于阶段 1 读取的原文做增量 EditFile：只更新有变化的段落，保留用户手动维护、且仍然准确的内容。不要静默整篇覆盖。
- 每一行都要经得起这个检验：“删掉这行，Agent 下一轮会不会犯错或不知情？”——经不起的就删掉。不要写“请保持剧情连贯”这类对谁都成立、对谁都没用的废话。
- 不要把整章正文或大段原文复制进总览。总览是状态地图和索引，不是正文仓库。
- 全部使用中文。

## 阶段 3：简要汇报

写完文件后，用简短的自然语言说明：本次扫描发现了多少章节和要素、更新或新建了哪些段落、有没有发现需要用户确认的不确定信息（例如无法判断某伏笔是否已回收）。不要在聊天里重复输出整个 NovAI.md 文件内容。`
